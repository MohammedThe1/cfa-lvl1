let language = "en";
try {
  language = localStorage.getItem("madar-language") === "ar" ? "ar" : "en";
} catch {}
export const getLanguage = () => language;
export function toggleLanguage() {
  language = language === "en" ? "ar" : "en";
  try {
    localStorage.setItem("madar-language", language);
  } catch {}
}
export function translate(text) {
  if (language === "en") return text;
  if (arabic[text]) return arabic[text];
  for (const key of Object.keys(arabic).sort((a, b) => b.length - a.length))
    text = text.split(key).join(arabic[key]);
  return text;
}
export function applyLanguage(root) {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title =
    language === "ar" ? "مدار | CFA Level I" : "Madar | CFA Level I";
  if (language === "en") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode()))
    if (!node.parentElement.closest("[data-original],.language-toggle"))
      node.textContent = translate(node.textContent);
  for (const el of root.querySelectorAll("[aria-label]"))
    if (!el.closest("[data-original]"))
      el.setAttribute("aria-label", translate(el.getAttribute("aria-label")));
}
